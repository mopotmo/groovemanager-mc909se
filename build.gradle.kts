plugins {
    application
}

val swtVersion = "3.135.0"
val jfaceVersion = "3.40.0"

// SWT ships one artifact per platform (windowing system, OS, architecture)
val swtPlatform: String = run {
    val os = System.getProperty("os.name").lowercase()
    val arch = when (val a = System.getProperty("os.arch")) {
        "amd64", "x86_64" -> "x86_64"
        "aarch64", "arm64" -> "aarch64"
        else -> a
    }
    when {
        os.contains("mac") -> "cocoa.macosx.$arch"
        os.contains("win") -> "win32.win32.$arch"
        else -> "gtk.linux.$arch"
    }
}
val isMac = System.getProperty("os.name").lowercase().contains("mac")

repositories {
    mavenCentral()
}

dependencies {
    implementation("org.eclipse.platform:org.eclipse.swt.$swtPlatform:$swtVersion")
    implementation("org.eclipse.platform:org.eclipse.jface:$jfaceVersion") {
        // the generic SWT artifact selects the platform via Maven profiles, which Gradle ignores
        exclude(group = "org.eclipse.platform", module = "org.eclipse.swt")
    }
    // Java's own MIDI on macOS doesn't send SysEx and doesn't see devices
    // plugged in later; CoreMIDI4J fixes both (and does nothing elsewhere)
    implementation("uk.co.xfactory-librarians:coremidi4j:1.6")
    // JFace loads some of its icons as SVG
    runtimeOnly("org.eclipse.platform:org.eclipse.swt.svg:3.133.100") {
        exclude(group = "org.eclipse.platform", module = "org.eclipse.swt")
    }
}

java {
    toolchain {
        languageVersion = JavaLanguageVersion.of(25)
    }
}

sourceSets {
    main {
        java.setSrcDirs(listOf("app/src"))
        resources.setSrcDirs(listOf("app/resources"))
        // the 2004 manifest with its ext/*.jar Class-Path is kept for reference only
        resources.exclude("META-INF/MANIFEST.MF")
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
}

val appJvmArgs = buildList {
    // SWT must run on the main thread on macOS
    if (isMac) add("-XstartOnFirstThread")
    // SWT loads its native libraries via JNI
    add("--enable-native-access=ALL-UNNAMED")
}

application {
    mainClass = "com.groovemanager.app.mc909se.Starter"
    applicationDefaultJvmArgs = appJvmArgs
}

// The app loads its icons from ./root, so run it from the app directory
tasks.named<JavaExec>("run") {
    workingDir = file("app")
}

tasks.register<JavaExec>("runSse") {
    group = "application"
    description = "Runs the Simple Sample Editor (basic version)."
    classpath = sourceSets["main"].runtimeClasspath
    mainClass = "com.groovemanager.app.sse.Starter"
    jvmArgs = appJvmArgs
    workingDir = file("app")
    javaLauncher = javaToolchains.launcherFor(java.toolchain)
}

// Native installers (dmg on macOS, msi on Windows, deb on Linux) with a
// bundled Java runtime. jpackage can only build for the platform it runs on,
// see .github/workflows/installers.yml.
version = findProperty("appVersion") as String? ?: "1.1.0"
val isWindows = System.getProperty("os.name").lowercase().contains("win")

val jpackageInput = layout.buildDirectory.dir("jpackage/input")
val jpackageOutput = layout.buildDirectory.dir("jpackage/output")

val prepareJpackage = tasks.register<Sync>("prepareJpackage") {
    from(tasks.jar)
    from(configurations.runtimeClasspath)
    from("app/root") {
        into("root")
        exclude("error.log")
    }
    into(jpackageInput)
}

tasks.register<Exec>("jpackage") {
    group = "distribution"
    description = "Builds a native installer for the current platform."
    dependsOn(prepareJpackage)
    val launcher = javaToolchains.launcherFor(java.toolchain)
    val type = findProperty("installerType") as String?
        ?: if (isMac) "dmg" else if (isWindows) "msi" else "deb"
    doFirst {
        delete(jpackageOutput)
        executable = launcher.get().metadata.installationPath.file("bin/jpackage").asFile.path
    }
    args(
        "--type", type,
        "--name", "MC-909 Sample Editor",
        "--app-version", version.toString(),
        "--vendor", "Manu Robledo",
        "--copyright", "Copyright 2004 Manu Robledo",
        "--description", "Sample editor for the Roland MC-909 (2004)",
        "--about-url", "https://github.com/mopotmo/groovemanager-mc909se",
        "--input", jpackageInput.get().asFile.path,
        "--main-jar", tasks.jar.get().archiveFileName.get(),
        "--main-class", "com.groovemanager.app.mc909se.Starter",
        "--add-modules", "java.base,java.desktop",
        "--jlink-options", "--strip-debug --no-man-pages --no-header-files",
        "--java-options", "-Dgroovemanager.root=\$APPDIR/root",
        "--dest", jpackageOutput.get().asFile.path,
        // generated by packaging/icon/IconGenerator.java
        "--icon", file("packaging/icon/icon." + if (isMac) "icns" else if (isWindows) "ico" else "png").path,
    )
    appJvmArgs.forEach { args("--java-options", it) }
    if (isMac) args("--mac-package-identifier", "com.groovemanager.mc909se")
    if (isWindows) args(
        "--win-menu", "--win-shortcut", "--win-dir-chooser",
        "--win-menu-group", "GrooveManager",
        "--win-upgrade-uuid", "d1e0b631-8cf2-430b-b43d-a6acbacfc325",
        "--license-file", "LICENSE",
    )
    if (!isMac && !isWindows) args(
        "--linux-package-name", "groovemanager-mc909se",
        "--linux-menu-group", "AudioVideo;Audio",
        "--linux-shortcut",
        "--license-file", "LICENSE",
    )
}
